/**
 * Читання власних джерел у гейтах: прибирання коментарів.
 *
 * ## Чому це окремий модуль
 *
 * Ця функція існувала в проєкті ЧОТИРМА копіями — у `test-runners`,
 * `security-canon`, `i18n-canon` і `logging-conventions`, — і кожна відрізнялася
 * від решти. Причина одна: майже кожен гейт тут читає власні джерела текстом і
 * шукає в них заборонену конструкцію, а поруч із кожною забороною стоїть
 * коментар, який її ЦИТУЄ. Не прибравши коментарі, перевірка червоніє на
 * власному поясненні.
 *
 * Цю пастку проєкт проходив уже тричі, і щоразу на новій копії:
 *
 *  1. `test-runners` оголосив сиротою сам себе — у його докблоці процитовано
 *     `import … from '@playwright/test'` із мертвого файлу, заради якого гейт і
 *     написаний;
 *  2. `security-canon` червонів на абзаці `svelte.config.js`, що пояснює, чому
 *     `unsafe-inline` там немає — і, гірше, робив це ЛИШЕ на Windows: варіант
 *     регулярки з `$` без прапорця `m` не збігався через `\r` від CRLF;
 *  3. `analytics-canon` червонів на коментарі про перевірку плейсхолдера
 *     підрядком — тобто на описі того самого анти-патерна, від якого захищає.
 *
 * Чотири копії означали чотири шанси повторити це вчетверте. Тепер поводження
 * одне, і воно перевірене окремо (`source-text.test.ts`).
 *
 * ## Що саме прибирається
 *
 * HTML-коментарі (розмітка `.svelte`), блокові та рядкові. Рядкові — з двома
 * умовами, і обидві вистраждані:
 *
 *  - розбиття по `/\r?\n/`, бо у робочому дереві файли лежать із CRLF, а `.` у
 *    JS не збігається з `\r`;
 *  - `//` не вважається початком коментаря, якщо перед ним `:` або лапка —
 *    інакше `https://example.com` обрізається до `https:`, і гейт перестає
 *    бачити домени, які мусить звіряти.
 */
export function withoutComments(source: string): string {
	return source
		.replace(/<!--[\s\S]*?-->/g, '')
		.replace(/\/\*[\s\S]*?\*\//g, '')
		.split(/\r?\n/)
		.map((line) => line.replace(/(?<![:'"])\/\/.*/, ''))
		.join('\n');
}
