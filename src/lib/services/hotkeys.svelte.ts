import { browser } from '$app/environment';
import { acceptsShortcut } from './keyboard';
import { storage } from './storage';

/**
 * Вимикач одиночних літерних скорочень — WCAG SC 2.1.4, рівень A
 * (HOTKEYS-v8 § 3, CRITICAL).
 *
 * ## Що вимагає критерій
 *
 * Якщо скорочення складається лише з літери, цифри, знака пунктуації чи
 * символу, мусить бути істинним хоча б одне з трьох: його можна **вимкнути**,
 * **перепризначити** або воно діє **лише у фокусі** відповідного компонента.
 *
 * На цій сторінці одиночних скорочень чотирнадцять — `T`, `L`, `M`, `C`, `F`,
 * `H`, `W`/`A`/`S`/`D`, `1`–`5`, `Space`, — усі висять на вікні, тобто третій
 * шлях виключений за побудовою. Перепризначення означало б екран налаштувань
 * клавіш, якого тут немає. Лишається перший, і реалізований саме він.
 *
 * ## Кому це потрібно насправді
 *
 * Тим, хто вводить текст голосом, і тим, у кого клавіатура дає зайві
 * натискання. Диктування розсипається на одиночні літери, і кожна з них
 * виконує команду: сказане слово перемикає тему, глушить звук і йде у
 * фулскрин. Саме тому критерій рівня A, а не AA.
 *
 * ## Межа вимикача: символьні клавіші, і тільки вони
 *
 * Вимкнено — це `Key*`, `Digit*`, `Numpad0`–`Numpad9` і `Space`, тобто рівно
 * те, про що критерій. `Escape`, `Enter` і стрілки лишаються: вони не є
 * символами, під SC 2.1.4 не підпадають, і кожна з них тут потрібна —
 * `Escape` єдиним способом закриває панель мов, стрілками рухаються сценою.
 * Тобто вимкнувши скорочення, людина не втрачає навігації взагалі.
 *
 * ## Дві дороги ввімкнути й вимкнути
 *
 *  - `?hotkeys=off` у адресі — працює на дотику, пересилається посиланням і
 *    зберігається; `?hotkeys=on` повертає. Той самий шлях, що `?debug=1`, і
 *    він тут не «про запас»: на морській сторінці екрана налаштувань немає.
 *  - перемикач у службовій панелі налаштувань (`DebugSettingsDropdown`).
 *
 * ## Чому module-level синглтон без `$effect`
 *
 * `$effect` у конструкторі такого класу кидає `effect_orphan`. Канон для цієї
 * форми — гідрація в конструкторі, наскрізний запис у мутаторі
 * (SVELTE-CORE-v8 § 1.9). Той самий устрій, що в `debugMode`.
 */

/** Ключ у сховищі. Префікс проєкту додає фасад (STORAGE-NAMESPACE-v8). */
const STORAGE_KEY = 'hotkeys';

/**
 * Символьні клавіші — ті, про які говорить SC 2.1.4.
 *
 * За `code`, а не за `key`: `code` не залежить ні від розкладки, ні від Shift
 * (HOTKEYS-v8 § 1.3), тож `KeyW` лишається `KeyW` і в українській розкладці.
 */
const CHARACTER_KEY = /^(?:Key[A-Z]|Digit[0-9]|Numpad[0-9]|Space)$/;

class HotkeysState {
	/**
	 * Типово ввімкнені. Вимикач — це саме вимикач: сайт без нього поводиться
	 * так само, як поводився, і жодне збережене значення не потрібне, щоб
	 * скорочення працювали.
	 */
	enabled = $state(true);

	constructor() {
		// `browser &&` обов'язково: під час пререндеру сховища немає. Фасад не
		// кидає, але й читати там нема чого.
		if (browser) {
			this.enabled = storage.get(STORAGE_KEY) !== '0';
		}
	}

	/**
	 * Застосовує `?hotkeys=` з адреси. Кличе кореневий макет з `onMount` —
	 * не раніше: під час пререндеру звернення до `searchParams` кидає
	 * «Cannot access url.searchParams on a page with prerendering enabled».
	 *
	 * Значення з адреси ЗАПАМ'ЯТОВУЄТЬСЯ, а не діє на один перегляд. Для того,
	 * хто диктує голосом, вимикач, який доводиться ставити щоразу, — це не
	 * вимикач; а посилання лишається єдиним способом дістатися до нього з
	 * морської сторінки.
	 */
	applyParam(value: string | null): void {
		if (value === 'off') this.set(false);
		else if (value === 'on') this.set(true);
	}

	/** Наскрізний запис у мутаторі — канон для module-level синглтона (§ 1.9). */
	set(enabled: boolean): void {
		this.enabled = enabled;
		storage.set(STORAGE_KEY, enabled ? '1' : '0');
	}

	/** @returns новий стан — щоб той, хто кличе, міг його залогувати. */
	toggle(): boolean {
		this.set(!this.enabled);
		return this.enabled;
	}
}

export const hotkeys = new HotkeysState();

/**
 * ЄДИНА брама для скорочень сторінки.
 *
 * Обробники клавіш звертаються сюди, а не до `acceptsShortcut` напряму: інакше
 * вимикач діяв би лише на ті клавіші, автор яких про нього пам'ятав, — а це
 * рівно той спосіб, яким у цьому проєкті вже загубилися два захисти обробника
 * (`keyboard.ts` існує саме тому). Що звертань немає повз цю функцію, тримає
 * `hotkeys.test.ts`.
 */
export function acceptsPageShortcut(event: KeyboardEvent): boolean {
	if (!hotkeys.enabled && CHARACTER_KEY.test(event.code)) return false;
	return acceptsShortcut(event);
}
